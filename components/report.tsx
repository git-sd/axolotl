// The full scan report: summary, every agent task with what it saw and did, the score
// breakdown, every site check with why it matters, the ranked fixes, and a Markdown download.
// No motion: expandable sections are native <details>.

import { DIMS, SITES, verdictOf } from "@/lib/sites";
import type { ScanResult } from "@/lib/scan";

const round = (n: number) => Math.round(n * 10) / 10;

const BLOCKED_LABEL: Record<string, string> = {
  none: "Nothing blocked it",
  captcha_or_bot_check: "A CAPTCHA or bot check",
  login_required: "A login wall",
  element_not_usable: "A control it could not use",
  content_not_found: "The content it needed was not there",
  page_error: "A page error",
  timed_out: "It ran out of time",
  other: "Something else",
};

function Marks({ earned, max }: { earned?: number; max?: number }) {
  if (earned === undefined || !max) return null;
  return (
    <span className="marks" data-full={earned >= max - 0.05} title="Marks earned out of marks available, from a total of 100">
      <b>{earned}</b> / {max}
    </span>
  );
}

// Two or three plain sentences: how it went overall, where it was strong and weak, and the
// quickest wins. Built only from the numbers in the result.
export function summarise(result: ScanResult, host: string): string {
  const score = result.score;
  const [verdict] = verdictOf(score);
  const order = result.dims.map((v, i) => [DIMS[i], v] as const).sort((a, b) => b[1] - a[1]);
  const done = result.tasks.filter((t) => t[2]).length;
  const unscored = result.stats?.unscored ?? 0;
  const counted = result.tasks.length - unscored;
  const parts = [
    `${host} scored ${score} out of 100 (${verdict.toLowerCase()}). The agents completed ${done} of ${counted} scored tasks${unscored ? `; ${unscored} more did not finish in time and were left out of the score, so run the scan again if you want them included` : ""}.`,
    `It is strongest on ${order[0][0]} (${order[0][1]}) and weakest on ${order[3][0]} (${order[3][1]}).`,
  ];
  const wins = result.fixes.filter((f) => f[3] > 0).slice(0, 3);
  if (wins.length) {
    const gain = wins.reduce((a, f) => a + f[3], 0);
    parts.push(`The ${wins.length === 1 ? "top fix is" : `top ${wins.length} fixes are`} worth an estimated ${gain} points together.`);
  }
  return parts.join(" ");
}

export function buildMarkdown(result: ScanResult, host: string, siteName: string): string {
  const L: string[] = [];
  L.push(`# Agent experience report: ${host}`, "", `**Score: ${result.score} / 100** (${verdictOf(result.score)[0]}) · Site type: ${siteName}`, "", summarise(result, host), "");
  if (result.stats) {
    L.push(`Scan: ${result.stats.agents} agents, ${result.stats.steps} actions${result.stats.seconds ? `, ${result.stats.seconds}s` : ""}${result.checks ? `, ${result.checks.length} site checks` : ""}.`, "");
  }
  L.push("## Score breakdown", "");
  DIMS.forEach((d, i) => {
    const w = result.weights ? ` (${Math.round(result.weights[i] * 100)}% of the score)` : "";
    L.push(`- **${d}: ${result.dims[i]}**${w}${result.dimNotes?.[i] ? ` — ${result.dimNotes[i]}` : ""}`);
  });
  L.push("", "## Agent tasks", "");
  result.tasks.forEach((t, i) => {
    const d = result.taskDetails?.[i];
    L.push(`### ${d?.unscored ? "–" : t[2] ? "✓" : "✕"} ${t[0]}${t[3] !== undefined && t[4] ? ` (${t[3]} / ${t[4]} marks)` : ""}`, "", t[1], "");
    if (d?.evidence) L.push(`**What the agent saw:** ${d.evidence}`, "");
    if (d?.pages.length) L.push(`**Pages visited:** ${d.pages.join(" → ")}`, "");
    if (d && !t[2] && !d.unscored) L.push(`**What stopped it:** ${BLOCKED_LABEL[d.blockedBy] ?? d.blockedBy}`, "");
    if (d?.problems.length) {
      L.push("**Problems it found:**", "");
      d.problems.forEach((p) => L.push(`- [${p.severity}] ${p.problem}${p.where ? ` _(${p.where})_` : ""}. Fix: ${p.fix}`));
      L.push("");
    }
  });
  if (result.checks?.length) {
    L.push("## Site checks", "");
    DIMS.forEach((d) => {
      const mine = result.checks!.filter((c) => c.dim === d);
      if (!mine.length) return;
      L.push(`### ${d}`, "");
      mine.forEach((c) => {
        L.push(`- ${c.ok ? "✓" : "✕"} **${c.label}**: ${c.detail}`);
        if (!c.ok && c.fix) L.push(`  - Fix: ${c.fix}`);
      });
      L.push("");
    });
  }
  L.push("## Ranked fixes", "");
  result.fixes.forEach((f, i) => {
    L.push(`${i + 1}. **[${f[0].toUpperCase()}]** ${f[1]}${f[3] > 0 ? ` (+${f[3]} pts)` : ""}${f[4] ? " — verified" : ""}`, `   - ${f[2]}`, ...(f[5] ? [`   - Source: ${f[5]}`] : []));
  });
  L.push("", "_Generated by Axolotl with TinyFish web agents. Fix points are estimates._", "");
  return L.join("\n");
}

export default function Report({
  result,
  host,
  fromCache,
  onReset,
}: {
  result: ScanResult;
  host: string;
  fromCache: boolean;
  onReset: () => void;
}) {
  const siteName = (SITES[result.type] ?? SITES.custom).name;
  const taskMarks = result.tasks.some((t) => t[4] !== undefined);
  const high = result.fixes.filter((f) => f[0] === "high").length;
  const med = result.fixes.filter((f) => f[0] === "med").length;
  const low = result.fixes.filter((f) => f[0] === "low").length;

  function download() {
    const blob = new Blob([buildMarkdown(result, host, siteName)], { type: "text/markdown" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = `axolotl-report-${host.replace(/[^a-z0-9.-]/gi, "")}.md`;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  const seconds = result.stats?.seconds;
  const time = seconds ? `${Math.floor(seconds / 60)}m ${String(seconds % 60).padStart(2, "0")}s` : null;

  return (
    <div>
      <section className="card summary">
        <div className="card-label">Summary</div>
        <p>{summarise(result, host)}</p>
        {result.stats && (
          <p className="stats">
            {result.stats.agents} agents · {result.stats.steps} actions
            {time ? ` · ${time}` : ""}
            {result.checks ? ` · ${result.checks.length} site checks` : ""}
            {result.stats.unscored ? ` · ${result.stats.unscored} not scored (no verdict in time)` : ""}
          </p>
        )}
      </section>

      <section className="card">
        <div className="card-label">
          Agent tasks
          {taskMarks && (
            <span className="card-total">
              {round(result.tasks.reduce((a, t) => a + (t[3] ?? 0), 0))} / {round(result.tasks.reduce((a, t) => a + (t[4] ?? 0), 0))} marks
            </span>
          )}
        </div>
        {result.tasks.map((t, i) => {
          const d = result.taskDetails?.[i];
          return (
            <details key={t[0]} className="item" open={!t[2] && !!d && !d.unscored}>
              <summary>
                <span className="dot" data-dot={d?.unscored ? "skip" : t[2] ? "pass" : "fail"}>
                  {d?.unscored ? "–" : t[2] ? "✓" : "✕"}
                </span>
                <span className="item-main">
                  <span className="t">{t[0]}</span>
                  <span className="d">{t[1]}</span>
                </span>
                <Marks earned={t[3]} max={t[4]} />
              </summary>
              {d && (
                <div className="item-body">
                  {d.evidence && (
                    <div className="field-row">
                      <b>What the agent saw</b>
                      <p>{d.evidence}</p>
                    </div>
                  )}
                  {!t[2] && !d.unscored && (
                    <div className="field-row">
                      <b>What stopped it</b>
                      <p>{BLOCKED_LABEL[d.blockedBy] ?? d.blockedBy}</p>
                    </div>
                  )}
                  {d.pages.length > 0 && (
                    <div className="field-row">
                      <b>Pages visited</b>
                      <ol className="pages">
                        {d.pages.map((p, k) => (
                          <li key={k}>{p}</li>
                        ))}
                      </ol>
                    </div>
                  )}
                  {d.problems.length > 0 && (
                    <div className="field-row">
                      <b>Problems it found</b>
                      {d.problems.map((p, k) => (
                        <div key={k} className="mini-fix">
                          <span className="pri" data-priority={p.severity === "medium" ? "med" : p.severity}>
                            {p.severity === "medium" ? "MED" : p.severity.toUpperCase()}
                          </span>
                          <div>
                            <b>{p.problem}</b>
                            {p.where && <span className="where">{p.where}</span>}
                            <span className="why">Fix: {p.fix}</span>
                          </div>
                        </div>
                      ))}
                    </div>
                  )}
                  {d.log.length > 0 && (
                    <details className="log">
                      <summary>
                        What it did, step by step ({d.steps} action{d.steps === 1 ? "" : "s"})
                      </summary>
                      <ol>
                        {d.log.map((l, k) => (
                          <li key={k}>{l}</li>
                        ))}
                      </ol>
                    </details>
                  )}
                </div>
              )}
            </details>
          );
        })}
      </section>

      <section className="card">
        <div className="card-label">Score breakdown</div>
        {DIMS.map((d, i) => (
          <div className="dim" key={d}>
            <div className="dim-head">
              <span>
                {d}
                {result.weights && <small className="dim-weight">{Math.round(result.weights[i] * 100)}% of score</small>}
              </span>
              <span>{result.dims[i]}</span>
            </div>
            <div className="bar">
              <div style={{ width: `${result.dims[i]}%` }} />
            </div>
            {result.dimNotes?.[i] && <p className="dim-note">{result.dimNotes[i]}</p>}
          </div>
        ))}
      </section>

      {!!result.checks?.length && (
        <section className="card">
          <div className="card-label">
            Site checks · {result.checks.filter((c) => c.ok).length} of {result.checks.length} passed
            {result.checks.some((c) => c.max) && (
              <span className="card-total">
                {round(result.checks.reduce((a, c) => a + (c.marks ?? 0), 0))} / {round(result.checks.reduce((a, c) => a + (c.max ?? 0), 0))} marks
              </span>
            )}
          </div>
          {DIMS.map((dim) => {
            const mine = result.checks!.filter((c) => c.dim === dim);
            if (!mine.length) return null;
            return (
              <div key={dim} className="check-group">
                <h3>
                  {dim}
                  <small>
                    {mine.filter((c) => c.ok).length} of {mine.length} passed
                  </small>
                </h3>
                {mine.map((c) => (
                  <details key={c.label} className="item">
                    <summary>
                      <span className="dot" data-dot={c.ok ? "pass" : "fail"}>
                        {c.ok ? "✓" : "✕"}
                      </span>
                      <span className="item-main">
                        <span className="t">{c.label}</span>
                        <span className="d">{c.detail}</span>
                      </span>
                      <Marks earned={c.marks} max={c.max} />
                    </summary>
                    <div className="item-body">
                      {c.why && (
                        <div className="field-row">
                          <b>Why it matters</b>
                          <p>{c.why}</p>
                        </div>
                      )}
                      {!c.ok && c.fix && (
                        <div className="field-row">
                          <b>How to fix it</b>
                          <p>{c.fix}</p>
                        </div>
                      )}
                    </div>
                  </details>
                ))}
              </div>
            );
          })}
        </section>
      )}

      <section className="card">
        <div className="card-label">
          Ranked fixes · {result.fixes.length}
          {result.fixes.length > 0 && (
            <span className="card-total">
              {high} high · {med} medium · {low} low
            </span>
          )}
        </div>
        {result.fixes.length === 0 && <p className="verdict-sub">No problems found.</p>}
        {result.fixes.map((f) => (
          <div key={f[1]} className="fix">
            <span className="pri" data-priority={f[0]}>
              {f[0].toUpperCase()}
            </span>
            <div>
              <b>
                {f[1]}
                {f[4] && <span className="verified">verified</span>}
              </b>
              <span className="why">{f[2]}</span>
              {f[5] && <span className="source">{f[5]}</span>}
              {f[3] > 0 && <em>+{f[3]} pts</em>}
            </div>
          </div>
        ))}
      </section>

      <div className="result-foot">
        <div className="actions">
          <button className="btn" onClick={onReset}>
            Scan another site
          </button>
          <button className="btn btn-ghost" onClick={download}>
            Download report (.md)
          </button>
        </div>
        <p className="fineprint">
          {fromCache
            ? "This site was scanned in the last hour, so these are those results. Fix points are estimates."
            : "Live results from TinyFish web agents and verified site checks. Fix points are estimates."}
        </p>
      </div>
    </div>
  );
}
